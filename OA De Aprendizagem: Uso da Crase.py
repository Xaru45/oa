import os

def limpa():
    os.system('cls' if os.name == 'nt' else 'clear')
def menu():
  print('\033[1m---USO DA CRASE---\033[0m')
  print('1. Revisão do assunto')
  print('2. Lista de questões')
  print('3. Encerrar')

opcao = ""
while opcao != "3":
  menu()
  opcao = input('Selecione a opcção desejada: ')

  if opcao == "1":
    limpa()
    print('Vamos aprender de uma vez por todas o uso da crase!!!')
    print('\n\nA crase é a fusão da preposição \033[1ma\033[0m com o artigo definido feminino \033[1ma\033[0m (ou \033[1mas\033[0m), ou com o início dos pronomes demonstrativos \033[1maquele(s)\033[0m, \033[1maquela(s)\033[0m, \033[1maquilo\033[0m. O sinal gráfico que marca a crase é o acento grave (`).')
    input('Aperte Enter para continuar')
    limpa()
    print('\033[1mREGRAS DE QUANDO USAR CRASE\033[0m')
    print('A crase pode ser usada nas seguintes situações:')
    input('Aperte Enter para continuar')
    limpa()
    print('\n\nAntes de palavras femininas.\nExemplos:')
    print('Fui \033[1mà\033[0m escola.')
    print('Fomos \033[1mà\033[0m praia.')
    print('Você vai \033[1mà\033[0m padaria agora?')
    input('Aperte Enter para continuar')
    limpa()
    print('Quando acompanham verbos que indicam destino (ir, voltar, vir).\nExemplos:')
    print('Fui \033[1mà\033[0m padaria.')
    print('Voltei \033[1mà\033[0m loja')
    input('Aperte Enter para continuar')
    limpa()
    print('Nas locuções adverbiais, prepositivas e conjutivas.\nExemplos:')
    print('Saímos \033[1mà\033[0m noite.')
    print('\033[1mÀ\033[0m medida que o tempo passa, aprendemos mais.')
    input('Aperte Enter para continuar')
    limpa()
    print('Antes de pronomes demonstrativos (aquela, aquele, aquilo).\nExemplos:')
    print('Nas férias, fui \033[1mà\033[0mquela cidade que você me indicou.')
    print('Refere-se \033[1mà\033[0mquilo que aconteceu ontem na festa')
    input('Aperte Enter para continuar')
    limpa()
    print('Antes da locução "à moda de" quando ela estiver subentendida.\nExemplos:')
    print('Fez um gol \033[1mà\033[0m Pelé (faz um gol \033[1mà\033[0m moda de Pelé)')
    print('Escreve \033[1mà\033[0m Machado de Assis (escreve \033[1mà\033[0m moda de Machado de Assis)')
    input('Aperte Enter para continuar')
    limpa()
    print('Uso da crase na indicação das horas.\nExemplos:')
    print('A reunião será \033[1màs\033[0m 10:40h.')
    print('Saio do IFAL \033[1màs\033[0m 12:20.')
    print('Por outro lado, quando acompanhadas de preposições (para, desde, após, perante, com), não se utiliza a crase.')
    print('Ficamos na reunião desde \033[1màs\033[0m 11:00')
    print('Saímos do IFAL após \033[1màs\033[0m 18:00')
    input('Aperte Enter para continuar')
    limpa()
    print('Diante dos Pronomes Relativos "A qual" / "As quais".\nExemplos:')
    print('A cidade \033[1mà\033[0m qual fomos é linda. (Quem vai, vai a algum lugar).')
    input('Aperte Enter para continuar')
    limpa()
    print('Agora que vimos todas as regras do uso correto da crase, veremos a seguir as situações que NÃO devemos usar a crase!!!')
    input('Aperte Enter para continuar')
    limpa()
    print('Antes de palavras masculinas.\nExemplos:')
    print('Eduardo tem um carro \033[1mà\033[0m álcool.')
    print('Bernardo comprou um jipe \033[1mà\033[0m diesel.')
    print('Carliane escreve \033[1mà\033[0m lapís.')
    input('Aperte Enter para continuar')
    limpa()
    print('Antes de verbos.\nExemplos:')
    print('Ele estava disposto a estudar.')
    print('Ela passava o dia a cantar.')
    input('Aperte Enter para continuar')
    limpa()
    print('Antes de pronomes pessoais do caso reto e do caso oblíquo.')
    print('Os pronomes do caso reto são: eu, tu, ele, nós, vós, eles.\nOs pronomes do caso oblíquo são: me, mim, comigo, te, ti, contigo, se, si, o, lhe.\nExemplos:')
    print('Falamos a ela sobre o ocorrido.')
    print('A professora se referiu a mim.')
    print('Deram o dinheiro a ele?')
    input('Aperte Enter para continuar')
    limpa()
    print('Antes dos pronomes demonstrativos (isso, esse, este, esta, essa)\nExemplos:')
    print('Quando você aderir a esse plano, a mensalidade ficará com um preço menor')
    print('A professora se referiu a isso que aconteceu na aula.')
    input('Aperte Enter para continuar')
    limpa()
    print('Entre palavras repetidas.\nExemplos:')
    print('Dia a dia')
    print('Cara a cara')
    input('Aperte Enter para continuar')
    limpa()
    print('Quando o "A" estiver no singular e a palavra seguinte no plural.\nExemplo:')
    print('Não me refiro a mulheres sem caráter.')